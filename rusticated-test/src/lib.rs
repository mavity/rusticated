//! Minimal `libtest` implementation for the Rusticated sysroot.
//!
//! Provides the types and entry points expected by `rustc --test`
//! (`test_main_static`, `test_main_static_abort`, `TestDescAndFn`, etc.)
//! and emits either human-readable output or libtest NDJSON (`--format=json`)
//! over `std::io::stdout()`.

